"""The shipped models reproduce their pinned numbers.

This is the test that catches a silent change: a descriptor added to the catalog, a feature
reordered, a prepare step altered, or a model refitted without meaning to. The numbers are in
``permeability_golden.json``, regenerated by ``scripts/permeability/golden.py``.

It pins the arithmetic to seven decimals, which is far tighter than any permeability assay —
deliberately. Loose tolerances here would let a real change through.
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pytest

from chemsuite.permeability import ENDPOINTS, by_id
from chemsuite.permeability import models as shipped
from chemsuite.permeability.predict import predict_permeability

GOLDEN = Path(__file__).with_name("permeability_golden.json")

pytestmark = pytest.mark.skipif(
    not GOLDEN.is_file() or not all(shipped.installed(e) for e in ENDPOINTS),
    reason="the permeability models are not built in this checkout",
)


@pytest.fixture(scope="module")
def golden() -> dict:
    return json.loads(GOLDEN.read_text(encoding="utf-8"))


@pytest.fixture(scope="module")
def said(golden) -> dict:
    """Every endpoint's prediction for the golden molecules, computed once."""
    results = predict_permeability(list(golden["names"].values()), ENDPOINTS)
    return {
        endpoint.id: results.per_endpoint[endpoint.id].as_prediction() for endpoint in ENDPOINTS
    }


@pytest.mark.parametrize("endpoint_id", [e.id for e in ENDPOINTS])
def test_the_predictions_are_the_pinned_ones(endpoint_id, golden, said) -> None:
    expected = golden["endpoints"][endpoint_id]
    found = said[endpoint_id]

    assert found.predicted == pytest.approx(np.asarray(expected["predicted"]), abs=1e-7)
    assert found.distance == pytest.approx(np.asarray(expected["distance"]), abs=1e-7)
    assert found.inside.tolist() == expected["inside"]


@pytest.mark.parametrize("endpoint_id", [e.id for e in ENDPOINTS if e.task == "regression"])
def test_the_intervals_are_the_pinned_ones(endpoint_id, golden, said) -> None:
    expected = golden["endpoints"][endpoint_id]
    found = said[endpoint_id]

    assert found.low == pytest.approx(np.asarray(expected["low"]), abs=1e-7)
    assert found.high == pytest.approx(np.asarray(expected["high"]), abs=1e-7)
    # an interval that does not contain its own prediction would be a calibration bug
    assert (found.low <= found.predicted).all()
    assert (found.predicted <= found.high).all()


@pytest.mark.parametrize("endpoint_id", [e.id for e in ENDPOINTS if e.task == "classification"])
def test_the_class_scores_are_the_pinned_ones(endpoint_id, golden, said) -> None:
    expected = golden["endpoints"][endpoint_id]
    found = said[endpoint_id]

    assert found.scores == pytest.approx(np.asarray(expected["scores"]), abs=1e-7)


def test_the_golden_file_covers_every_endpoint(golden) -> None:
    assert sorted(golden["endpoints"]) == sorted(e.id for e in ENDPOINTS)
    for endpoint_id, entry in golden["endpoints"].items():
        assert entry["task"] == by_id(endpoint_id).task
        assert len(entry["predicted"]) == len(golden["names"])


def test_the_textbook_ordering_holds(golden, said) -> None:
    """A sanity check on the chemistry, not an evaluation: propranolol crosses a Caco-2
    monolayer and atenolol does not, which is the pair the assay is taught with."""
    order = list(golden["names"])
    propranolol, atenolol = order.index("propranolol"), order.index("atenolol")
    caco2 = said["caco2"]

    assert caco2.predicted[propranolol] > caco2.predicted[atenolol]
