"""Ranked sites of metabolism from the shipped model.

Two kinds of test here. The chemistry ones name a known metabolic route and ask the model
for it, which is what says the vendored archive is the trained model rather than a working
pipeline over nonsense. :func:`test_the_shipped_model_reproduces_the_golden_scores` pins
the whole path -- features, trees, archive -- against
``tests/metabolism/som_golden.json``, regenerated by ``scripts/som/golden.py``.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest
from rdkit import Chem

from chemsuite.metabolism import ISOFORMS
from chemsuite.metabolism.sites import predict_sites, top_site

GOLDEN = Path(__file__).with_name("som_golden.json")


def mol(smiles: str) -> Chem.Mol:
    found = Chem.MolFromSmiles(smiles)
    assert found is not None
    return found


def test_a_molecule_is_scored_for_every_isoform_at_once():
    ranked = predict_sites(mol("CCO"))
    assert tuple(ranked) == ISOFORMS
    for isoform, sites in ranked.items():
        assert sorted(site.atom for site in sites) == [0, 1, 2]  # every heavy atom, once
        assert all(0.0 <= site.score <= 1.0 for site in sites)
        assert all(site.isoform == isoform for site in sites)


def test_scoring_one_isoform_matches_scoring_all_of_them():
    molecule = mol("CC(=O)Nc1ccc(O)cc1")
    every = predict_sites(molecule)
    for isoform in ("3A4", "2D6"):
        alone = predict_sites(molecule, (isoform,))[isoform]
        assert [site.atom for site in alone] == [site.atom for site in every[isoform]]
        assert [site.score for site in alone] == [site.score for site in every[isoform]]


def test_sites_come_back_best_first_with_ties_broken_by_the_lower_atom():
    # ibuprofen's two isobutyl methyls are symmetry-equivalent, so they score identically
    molecule = mol("CC(C)Cc1ccc(C(C)C(=O)O)cc1")
    ranked = predict_sites(molecule, ("2C9",))["2C9"]
    scores = [site.score for site in ranked]
    assert scores == sorted(scores, reverse=True)
    assert ranked[0].score == pytest.approx(ranked[1].score)
    assert ranked[0].atom < ranked[1].atom


@pytest.mark.parametrize(
    ("name", "smiles", "isoform", "expected", "element"),
    [
        # 3A4 hydroxylates testosterone at C6, allylic to the enone: atom 7 here
        ("testosterone", "CC12CCC3C(CCC4=CC(=O)CCC34C)C1CCC2O", "3A4", 7, "C"),
        # paracetamol's amide nitrogen, the route to NAPQI
        ("paracetamol", "CC(=O)Nc1ccc(O)cc1", "3A4", 3, "N"),
        # caffeine's C8, oxidized to 1,3,7-trimethyluric acid
        ("caffeine", "Cn1cnc2c1c(=O)n(C)c(=O)n2C", "3A4", 2, "C"),
        # 2E1 oxidizes ethanol at the carbon bearing the hydroxyl
        ("ethanol", "CCO", "2E1", 1, "C"),
    ],
)
def test_the_model_finds_the_known_site(name, smiles, isoform, expected, element):
    molecule = mol(smiles)
    best = top_site(molecule, isoform)
    assert best is not None
    assert best.atom == expected, f"{name}: top site was atom {best.atom}"
    assert molecule.GetAtomWithIdx(best.atom).GetSymbol() == element


def test_explicit_hydrogens_change_nothing_and_are_never_offered_as_sites():
    implicit = mol("CC(=O)Nc1ccc(O)cc1")
    explicit = Chem.AddHs(implicit)
    plain = predict_sites(implicit, ("3A4",))["3A4"]
    with_hydrogens = predict_sites(explicit, ("3A4",))["3A4"]
    assert len(with_hydrogens) == implicit.GetNumAtoms()
    assert [site.atom for site in with_hydrogens] == [site.atom for site in plain]
    assert [site.score for site in with_hydrogens] == [site.score for site in plain]
    assert all(explicit.GetAtomWithIdx(site.atom).GetAtomicNum() != 1 for site in with_hydrogens)


def test_a_molecule_with_no_atoms_has_no_sites():
    assert predict_sites(Chem.MolFromSmiles(""), ("3A4",)) == {"3A4": []}
    assert top_site(Chem.MolFromSmiles(""), "3A4") is None


def test_an_isoform_the_model_was_not_trained_for_is_refused():
    with pytest.raises(ValueError, match="unknown isoform"):
        predict_sites(mol("CCO"), ("2C18",))
    with pytest.raises(ValueError, match="no isoform"):
        predict_sites(mol("CCO"), ())


def test_the_applicability_domain_marks_what_the_training_set_never_held():
    # a drug-like amide sits inside the training data
    for site in predict_sites(mol("CC(=O)Nc1ccc(O)cc1"), ("3A4",))["3A4"]:
        assert site.domain == 1.0
        assert site.inside_domain
    # a tetraalkyl silane does not: silicon is not in the training set at all
    exotic = predict_sites(mol("C[Si](C)(C)CCB(F)F"), ("3A4",))["3A4"]
    assert any(site.domain < 1.0 for site in exotic)
    assert not all(site.inside_domain for site in exotic)


def test_the_shipped_model_reproduces_the_golden_scores():
    golden = json.loads(GOLDEN.read_text(encoding="utf-8"))
    assert golden["isoforms"] == list(ISOFORMS)
    for smiles, expected in golden["molecules"].items():
        ranked = predict_sites(mol(smiles))
        for isoform, scores in expected.items():
            found = {site.atom: site.score for site in ranked[isoform]}
            assert [found[atom] for atom in range(len(scores))] == pytest.approx(
                scores, abs=5e-7
            ), f"{smiles}, {isoform}"
